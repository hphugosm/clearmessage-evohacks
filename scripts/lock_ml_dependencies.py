#!/usr/bin/env python3
"""Explicit setup: lock the actually installed ML dependency closure and wheels."""

import importlib.metadata as metadata
import json
from pathlib import Path
from urllib.request import urlopen

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name


def closure(names):
    found = {}
    while names:
        name = canonicalize_name(names.pop())
        if name in found:
            continue
        dist = metadata.distribution(name)
        found[name] = dist.version
        for line in dist.requires or []:
            req = Requirement(line)
            if req.marker is None or req.marker.evaluate({"extra": ""}):
                names.append(req.name)
    return found


def main():
    baseline = closure(["scikit-learn"])
    encoder = closure(["sentence-transformers", "torch", "transformers", "safetensors"])
    licenses = {}
    for filename, packages, prefix in [
        ("requirements.txt", baseline, ""),
        ("requirements-encoder.txt", {k: v for k, v in encoder.items() if k not in baseline}, "-r requirements.txt\n"),
    ]:
        lines = ["# Verified installed versions; generated by scripts/lock_ml_dependencies.py.\n", prefix]
        for name, version in sorted(packages.items()):
            with urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=20) as response:
                release = json.load(response)
            hashes = sorted({item["digests"]["sha256"] for item in release["urls"]
                             if item["packagetype"] == "bdist_wheel" and not item["yanked"]})
            if not hashes:
                raise SystemExit("dependency_wheel_missing")
            lines.append(f"{name}=={version} \\\n" + " \\\n".join(f"    --hash=sha256:{value}" for value in hashes) + "\n")
            info = release["info"]
            licenses[name] = {"version": version, "license_expression": info.get("license_expression"),
                              "license_classifiers": [c for c in info.get("classifiers", []) if c.startswith("License ::")],
                              "metadata_url": f"https://pypi.org/pypi/{name}/{version}/json"}
        (Path("ml") / filename).write_text("".join(lines))
        print(json.dumps({"lock": f"ml/{filename}", "packages": len(packages)}), flush=True)
    Path("ml/dependency-licenses.json").write_text(json.dumps(licenses, indent=2, sort_keys=True) + "\n")


if __name__ == "__main__":
    main()
